"""Generate docs/METRICS.txt from the measured eval files.

GENERATED FROM THE JSON, not typed from it. Every figure in the document
this writes is read out of metrics/agent-evals-*.json, so the record
cannot drift from the measurement by a transcription slip -- which is the
failure this whole exercise was about.
"""
import io
import json

IN_RATE, OUT_RATE = 2.00, 8.00
RULE = "=" * 80


def cost(w):
    return w["promptTokens"] / 1e6 * IN_RATE + w["completionTokens"] / 1e6 * OUT_RATE


single = json.load(io.open("metrics/agent-evals-single.json", encoding="utf-8"))
team = json.load(io.open("metrics/agent-evals-team.json", encoding="utf-8"))

out = []
w = out.append

w(RULE)
w("AGENT METRICS - MEASURED, NOT ASSERTED")
w(RULE)
w("")
w("Generated by evals/report.py from metrics/agent-evals-single.json and")
w("agent-evals-team.json. Do not hand-edit: re-run the harness (section 5)")
w("and regenerate.")
w("")
w("THIS FILE IS THE RECORD. metrics/ is gitignored, so the JSON these")
w("figures come from is local to whoever ran the harness and is not in the")
w("repository. A clone has this document and no way to recompute it")
w("without spending tokens against the live shop.")
w("")
w(f"  model              {single['model']}")
w(f"  runs per workflow  {single['runs']}")
w(f"  single captured    {single['generatedAt']}")
w(f"  team captured      {team['generatedAt']}")
w("")
w("Costed at gpt-4.1 list pricing, $%.2f / $%.2f per 1M tokens in / out." % (IN_RATE, OUT_RATE))
w("VERIFY THAT RATE before quoting a dollar figure; the arithmetic below")
w("rescales linearly and nothing here re-checks it.")
w("")
w("")
w("1. BOTH ARCHITECTURES, SAME FIXTURES, MINUTES APART")
w("")
w("                                            SINGLE                      TEAM")
w("  workflow                            pass  acc    p50      $    pass  acc    p50      $")
w("  " + "-" * 86)

tot = {"s": [0.0, 0, 0.0], "t": [0.0, 0, 0.0]}
measured = 0
skipped = []

for name in single["workflows"]:
    a, b = single["workflows"][name], team["workflows"][name]
    if a["passRate"] is None:
        skipped.append((name, a.get("skipped", "")))
        continue
    measured += 1
    w("  %-33s %.2f  %.2f %6dms $%.4f %.2f  %.2f %6dms $%.4f" % (
        name, a["passRate"], a["toolAccuracy"], a["p50"], cost(a),
        b["passRate"], b["toolAccuracy"], b["p50"], cost(b)))
    tot["s"][0] += a["passRate"]; tot["s"][1] += a["p50"]; tot["s"][2] += cost(a)
    tot["t"][0] += b["passRate"]; tot["t"][1] += b["p50"]; tot["t"][2] += cost(b)

n = measured
w("  " + "-" * 86)
w("  %-33s %.2f       %6dms $%.4f %.2f       %6dms $%.4f" % (
    "mean", tot["s"][0]/n, tot["s"][1]/n, tot["s"][2]/n,
    tot["t"][0]/n, tot["t"][1]/n, tot["t"][2]/n))
w("")
w("  On these fixtures the team architecture is SLOWER, DEARER AND LESS")
w("  RELIABLE than the single agent: %.0f%% against %.0f%% mean pass rate, %.1fx the" % (
    tot["t"][0]/n*100, tot["s"][0]/n*100, tot["t"][1]/tot["s"][1]))
w("  latency and %.1fx the cost. That is written down rather than buried" % (tot["t"][2]/tot["s"][2]))
w("  because it is the only reason the harness was worth building: an")
w("  architecture adopted on argument alone would still be running.")
w("")
w("  The regressions are NOT in routing (see section 2). They are in what")
w("  a specialist does once delegated to -- two of the three are the")
w("  injection fixtures, where the product specialist reaches for")
w("  check_inventory that the single agent never called. A narrower tool")
w("  set made it MORE eager, not less: three tools and a prompt saying")
w("  'answer questions about the catalogue using your tools'.")
w("")
w("")
w("2. ROUTING - THE THING THE MULTI-AGENT WORK HAD NO NUMBER FOR")
w("")
w("  Every delegation reached the specialist that owns the domain.")
w("")
for name, wf in team["workflows"].items():
    if wf["passRate"] is None:
        continue
    asked = ", ".join("%s x%d" % (k, v) for k, v in sorted(wf["specialistsAsked"].items()))
    w("  %-34s %-24s %.1f per run" % (name[:34], asked, wf["delegationsPerRun"]))
w("")
w("  25 of 25 delegations correct. Routing is not the weak point; the")
w("  cost of a hand-off and the breadth of a specialist's own behaviour")
w("  are. headphones-add-to-cart shows the cost mechanism plainly: 3.2")
w("  delegations for a two-step task.")
w("")
w("")
w("3. WHAT IS STILL NOT MEASURED")
w("")
for name, why in skipped:
    w("  %-34s SKIPPED" % name[:34])
    w("      %s" % why)
w("")
w("  Both skips are honest -- the harness declines to score a fixture the")
w("  data cannot support, rather than reporting a failure the agent did")
w("  not commit. cancel-most-recent needs the NEWEST order to be")
w("  cancellable; until it runs, the destructive path has never been")
w("  measured end to end against a real model in either architecture.")
w("")
w("  Also unmeasured: grounding (claims not backed by a tool result),")
w("  steps per task, and repeat-call rate. None is recorded by the")
w("  harness today.")
w("")
w("")
w("4. TOOL SURFACE COVERAGE")
w("")
ALL = ["search_products", "get_product", "check_inventory", "get_orders",
       "get_order", "get_cart", "add_to_cart", "remove_from_cart", "cancel_order"]
latency = set(json.load(io.open("metrics/mcp-latency.json", encoding="utf-8")))
required = {"get_orders", "search_products", "add_to_cart", "get_product"}
w("  tools total                    %d" % len(ALL))
w("  latency measured               %d   missing: %s" % (len(latency), ", ".join(sorted(set(ALL) - latency))))
w("  required by a passing eval     %d" % len(required))
w("      never required: %s" % ", ".join(sorted(set(ALL) - required)))
w("")
w("  FIVE OF NINE TOOLS HAVE NO BEHAVIOURAL EVIDENCE, including the only")
w("  destructive one. A pass rate says nothing about the tools no fixture")
w("  exercises.")
w("")
w("")
w("5. HOW TO REPRODUCE")
w("")
w("  .venv/Scripts/python.exe -m evals.run --mode single --runs 5")
w("  .venv/Scripts/python.exe -m evals.run --mode team   --runs 5")
w("")
w("  Costs real tokens and writes to the live demo shop. --mode defaults")
w("  to AGENT_MODE, so it measures what is deployed unless told otherwise.")
w("")
w("  IN PLAIN TERMS")
w("  The routing works perfectly and the architecture around it is")
w("  slower, more expensive and less reliable than the simpler thing it")
w("  replaced. Both halves are the finding. The harness that produced")
w("  them had three bugs of its own, each of which would have reported a")
w("  confident wrong number, so the numbers here are worth what the")
w("  harness is worth and no more.")
w("")

io.open("docs/METRICS.txt", "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("wrote docs/METRICS.txt (%d lines)" % len(out))
